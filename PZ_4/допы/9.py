# посчитать и вывести количество элементов арифметической прогресии, удовлетворяющих условию 10< ai < 30
a = int(input("Введите первый элемнт: "))
raz = int(input("Введите разность прогресии: "))
n = int(input("Введите количество элементов: "))
i = 0
k = 0
while i < n:
    if 10 < a < 30:
        k += 1
    a = a + raz
    i += 1
print("Количество элементов: ", k)