# ввести N чисел. найти и вывести их среднее арифметическое

n = int(input("Введите число:"))
i = 0
t = 0

while i < n:
    num = float(input("Введите число: "))
    t += num
    i += 1
if n > 0:
    arf = t / n
    print("Среднее арифметическое: ", arf)
else:
    print("Количество чисел должно быть > 0")