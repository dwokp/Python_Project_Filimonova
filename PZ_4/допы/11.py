# дна арифметическая прогрессия a1=1, a2=4, a3=7, a4=10, a5=13, ... составить программу которая каждый элемент
# прогрессии разделит на 2 и результат округлит до ближайшего целого
n = int(input("Введите количество элементов: "))
a = 1
i = 0
while i < n:
    print(round(a / 2))
    a = a + 3
    i = i + 1