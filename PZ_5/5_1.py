# Найти сумму чисел ряда 1,2,3,4... от числа n до числа m. Суммирование оформить функцией с параметрами.
# Значения n и m  программа должна запрашивать.
def summa(n, m): # функция для нахождения суммы чисел от n  до m
    s = 0 # переменная для суммы
    while n <= m:
        s += n
        n += 1
    return s

# ввод числа n
n = input("Введите n: ")
while type(n) != int:
    try:
        n = int(n) # преобразование ввода в целое число
    except ValueError:
        print("Неправильно ввели!")
        n = input("Введите n: ")

# ввод числа m
m = input("Введите m: ")
while type(m) != int:
    try:
        m = int(m) #  преобразование ввода в целое число
    except ValueError:
        print("Неправильно ввели!")
        m = input("Введите m: ")

# проверяем условие
if n <= m:
    print("Сумма чисел:", summa(n, m))
else:
    print("Ошибка! n должно быть меньше или равно m")