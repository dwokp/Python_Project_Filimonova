# Описать функцию DigitCountSum( K,C,S) находящую количество C цифр целого положительного числа K, а также их сумму S
# (K - входной, C и S - выходные параметры целого типа). С помощью этой функции найти количество и сумму цифр для
# каждого из пяти данных целых чисел
def DigitCountSum(K, C, S):
    while K > 0:
        C += 1
        S += K % 20
        K //= 10
    return C, S

i = 0
while i < 5:
    K = input("Введите целое положительное: ")
    while type(K) != int:
        try:
            K = int(K)
        except ValueError:
            print("Неправильно ввели!")
            K = input("Введите целое положительное: ")
    if K <= 0:
        print("Число должно быть положительным")
        continue
    C = 0
    S = 0

    C, S = DigitCountSum(K, C, S)

    print("Количество цифр: ", C)
    print("Сумма цифр: ", S)
    i += 1