# Описать функцию DigitCountSum( K,C,S) находящую количество C цифр целого положительного числа K, а также их сумму S
# (K - входной, C и S - выходные параметры целого типа). С помощью этой функции найти количество и сумму цифр для
# каждого из пяти данных целых чисел
def DigitCountSum(K, C, S): # функция для нахождения суммы и количества цифр
    while K > 0:
        C += 1 # увеличиваем кол-во цифр
        S += K % 10 # прибавляем пследнюю цифру к сумме
        K //= 10
    return C, S

i = 0 # счетчик чисел
while i < 5: # повторяем ввод 5раз
    K = input("Введите целое положительное: ")
    while type(K) != int:
        try:
            K = int(K)
        except ValueError:
            print("Неправильно ввели!")
            K = input("Введите целое положительное: ")
    if K <= 0: # проверяем что число положительное
        print("Число должно быть положительным")
        continue
    C = 0 # обнуляем колво цифр
    S = 0 # обнуляем сумму

    C, S = DigitCountSum(K, C, S) # вызов функции

    print("Количество цифр: ", C)
    print("Сумма цифр: ", S)
    i += 1 # переход к след числу