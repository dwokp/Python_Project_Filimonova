try:
    # ввод координат х, у
    x = float(input("Введите значение x: "))
    y = float(input("Введите значение y: "))

    if (x + y) % 2 == 0:
        print("Данное поле является черным")
    else:
        print("Данное поле является белым")
except ValueError:
    print("Ошибка, введите число")