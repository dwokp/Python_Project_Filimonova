# с начала суток прошло N секунд (N- целое). найти количество полных часов прошедших с начала суток
try:
    # ввод секунд и преобразование в целое число
    N = int(input("Введите количество секунд: "))
    # целочисленное деление на 3600 для получения полных часов
    full_hour = N // 3600
    # вывод результата
    print(f"Полных часов прошло: {full_hour} ")
except ValueError:
    # обработка ошибки при вводе нечислового значения
    print("Ошибка, нужно ввести целое число")
