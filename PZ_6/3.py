# Даны множества A и B, состоящие соответственно из N1 и N2 точек (точки заданы своими координатами x, у).
# Найти минимальное расстояние между точками этих множеств и сами точки, расположенные на этом расстоянии (вначале
# выводится точка из множества A, затем точка из множества B). Расстояние R между точками с координатами (x1, y 1) и
# (x2, у2) вычисляется по формуле: R = √(x2 – x1)^2 + (у2 – y1)^2. Для хранения данных о каждом наборе точек следует
# использовать по два списка: первый список для хранения абсцисс, второй — для хранения ординат.

import random
import math

n1 = int(input("Введите количество точек A: "))
n2 = int(input("Введите количество точек B: "))

x1 = []
y1 = []
x2 = []
y2 = []

for i in range(n1):  #заполняем списки координатами точки а
    x = random.randint(1, 100)
    y = random.randint(1, 100)
    x1.append(x) #абсцисса
    y1.append(y) #ордината

for i in range(n2): #заполняем списки координатами точки а
    x = random.randint(1, 100)
    y = random.randint(1, 100)
    x2.append(x)
    y2.append(y)

min_r = float('inf') #задаем начальное минимальное расстояние
min_i = 0 # индекс точки а
min_j = 0 # индекс точки б

for i in range(n1): #сравниваем каждую точку а с каждой точкой б
    for j in range(n2):
        r = math.sqrt((x2[j] - x1[i])**2 + (y2[j] - y1[i])**2) #вычисляем расстояние между 2мя точками
        if r < min_r: #если расстояние меньше предыдущего минимума
            min_r = r #сохраняем новое минимальное расстояние
            min_i = i #запоминаем индекс точки а
            min_j = j #запоминаем индекс точки б

print("Минимальное расстояние:", min_r)
print("Точка A:", x1[min_i], y1[min_i])
print("Точка B:", x2[min_j], y2[min_j])
