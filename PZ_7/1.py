#Дано целое число N(>0) и строка S. преобразовать строку S в строку длины N следующим образом:
# если длина строки S больше N, то отбросить первые символы,если длина строки S меньше N, то в
# ее начало добавить символы "."(точка)

n = int(input("Введите целое число N: "))
s = input("Введите строку S: ")

#проверяем длину строки
if len(s) > n:
    s = s[-n] # оставляем последние n символов
elif len(s) < n:
    s = "." * (n - len(s)) + s # добавляем точки в начало строки

print("результат: ", s)