#даны строки s, s1, s2. заменить в строке s последнее вхождение строки s1 на строку s2
s = input("Введите строку s: ")
s1 = input("Введите строку s1: ")
s2 = input("Введите строку s2: ")

parts = s.rsplit(s1, 1) #разделяем строку по последнему вхождению s1
#если s1 найдена,то заменяем ее на s2
if len(parts) > 1:
    s = s2.join(parts)

print(s)